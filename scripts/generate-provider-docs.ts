import fs from 'node:fs/promises';
import { providers, PRICING_DATE } from './providers/catalog.js';
const file = new URL('../TRANSCRIPTION_PROVIDERS.md', import.meta.url);
const source = await fs.readFile(file, 'utf8');
const rows = providers.map((provider) => {
  const model = provider.models.find((item) => item.id === provider.defaultModel);
  const mode =
    provider.id === 'local'
      ? 'Local chunks'
      : provider.id === 'elevenlabs'
        ? 'Full movie or chunks; native word timing and speakers'
        : `Chunks; ${model?.timing ?? 'configured'} timing`;
  return `| \`${provider.id}\` | \`${provider.defaultModel || 'explicitly selected'}\` | ${mode} |`;
});
const table = `<!-- providers:start -->\n<!-- Generated by npm run docs:providers from catalog.ts; do not edit this table. -->\n\nCatalog snapshot: ${PRICING_DATE}. The UI warns when it is more than 30 days old.\n\n| Provider | Default model | Application mode |\n| --- | --- | --- |\n${rows.join('\n')}\n\n<!-- providers:end -->`;
const start = source.includes('<!-- providers:start -->')
  ? source.indexOf('<!-- providers:start -->')
  : source.indexOf('| Provider', source.indexOf('## Implemented adapters'));
const end = source.includes('<!-- providers:end -->')
  ? source.indexOf('<!-- providers:end -->') + '<!-- providers:end -->'.length
  : source.indexOf("OpenRouter's", start);
const content = source.slice(0, start) + table + '\n\n' + source.slice(end).trimStart();
if (process.argv.includes('--check')) {
  // Prettier adjusts table spacing; compare after removing insignificant spacing.
  const simplify = (text: string) =>
    text
      .replace(/\s+/g, ' ')
      .replace(/\|\s+/g, '|')
      .replace(/\s+\|/g, '|')
      .replace(/-+/g, '-')
      .trim();
  if (simplify(content) !== simplify(source))
    throw new Error('Provider documentation is stale; run npm run docs:providers and format.');
} else await fs.writeFile(file, content);
